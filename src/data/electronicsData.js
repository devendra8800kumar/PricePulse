// Helper to format currency
export const formatCurrency = (amount, currency = 'INR') => {
  if (amount === undefined || amount === null || isNaN(amount)) return '₹0';
  if (currency === 'USD') {
    return `$${Number(amount).toLocaleString('en-US')}`;
  }
  return `₹${Number(amount).toLocaleString('en-IN')}`;
};

// Helper to look up product by ID or slug
export const getProductById = (identifier) => {
  if (!identifier) return null;
  const cleanId = String(identifier).toLowerCase().trim();
  return TRENDING_PRODUCTS.find(p => 
    p.id.toLowerCase() === cleanId || 
    (p.slug && p.slug.toLowerCase() === cleanId) ||
    cleanId === p.id.toLowerCase().replace('prod-', '') ||
    p.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').includes(cleanId)
  ) || null;
};

